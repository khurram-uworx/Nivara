"""Polars benchmark for NivaraIncident analytical operations.

Reads the same Parquet files generated by NivaraIncident.Cli and runs
equivalent Polars operations with wall-clock timing.

Usage:
    python samples/NivaraIncident/Python/benchmark.py --dataset <path>
"""
import argparse
import time
import sys
from pathlib import Path

import polars as pl


def parse_args():
    p = argparse.ArgumentParser(description="Polars benchmark for NivaraIncident")
    p.add_argument("--dataset", required=True, help="Path to directory containing Parquet files")
    p.add_argument("--scenario", default="A", help="Scenario ID for incident window (default: A)")
    return p.parse_args()


def get_incident_ticks(scenario_id: str, requests_path: str) -> tuple[int, int]:
    """Return (incident_start_ticks, incident_end_ticks) matching C# Scenario definitions.

    Derives the base time from the actual data minimum timestamp rather than
    hardcoding, since the .NET DateTimeOffset.Ticks value depends on the
    generator's base time which may differ from the source code constant.
    .NET tick = 100ns.  1 minute = 600_000_000 ticks.
    """
    minute = 600_000_000
    windows = {
        "A": (5, 25),
        "B": (17, 30),
        "C": (10, 20),
        "D": (8, 22),
    }
    start_min, end_min = windows[scenario_id]

    # Derive base from actual data (minimum non-zero timestamp aligned to minute boundary)
    df = pl.scan_parquet(requests_path).filter(pl.col("Timestamp") > 0).select("Timestamp").collect()
    data_min = int(df["Timestamp"].min())
    base = data_min - (data_min % minute)

    return base + start_min * minute, base + end_min * minute


def time_fn(label: str, fn):
    """Run fn(), print timing + row count, return the result."""
    t0 = time.perf_counter()
    result = fn()
    elapsed_ms = (time.perf_counter() - t0) * 1000
    rows = result.height if isinstance(result, pl.DataFrame) else "?"
    print(f"  {label:<24s} {elapsed_ms:>8.1f} ms  ({rows} rows)")
    return result


def analysis_degradation(requests_path: str, start: int, end: int) -> pl.DataFrame:
    return (
        pl.scan_parquet(requests_path)
        .filter(pl.col("Timestamp").is_between(start, end))
        .sort("Timestamp")
        .with_columns(
            pl.col("StatusCode")
            .cast(pl.Float64)
            .rolling_mean(window_size=60)
            .alias("ErrorRate")
        )
        .with_columns(pl.col("ErrorRate").shift(1).alias("PrevErrorRate"))
        .select(["Service", "Endpoint", "Timestamp", "StatusCode", "ErrorRate", "PrevErrorRate"])
        .collect()
    )


def analysis_deployment(requests_path: str, deployments_path: str, start: int, end: int) -> pl.DataFrame:
    requests = (
        pl.scan_parquet(requests_path)
        .filter(pl.col("Timestamp").is_between(start, end))
        .sort("Timestamp")
        .collect()
    )
    deployments = pl.scan_parquet(deployments_path).collect()

    # Latest deployment per service
    latest_deploy = (
        deployments
        .sort("Timestamp", descending=True)
        .group_by("Service")
        .first()
        .select([
            pl.col("Service"),
            pl.col("Version").alias("DeploymentVersion"),
            pl.col("Timestamp").alias("DeployTimestamp"),
        ])
    )

    result = (
        requests
        .join(latest_deploy, on="Service", how="left")
        .with_columns([
            pl.when(pl.col("DeployTimestamp").is_not_null() & (pl.col("DeployTimestamp") <= pl.col("Timestamp")))
            .then((pl.col("Timestamp") - pl.col("DeployTimestamp")) / 10_000_000.0)
            .otherwise(-1.0)
            .alias("TimeSinceDeploySec"),
            pl.when(pl.col("StatusCode") >= 500).then(pl.lit("server_error"))
            .when(pl.col("StatusCode") >= 400).then(pl.lit("client_error"))
            .otherwise(pl.lit("success"))
            .alias("ErrorCategory"),
        ])
        .select([
            "Service", "Endpoint", "Timestamp", "StatusCode", "Region",
            "DeploymentVersion", "TimeSinceDeploySec", "ErrorCategory",
        ])
    )
    return result


def analysis_saturation(instances_path: str, start: int, end: int) -> pl.DataFrame:
    return (
        pl.scan_parquet(instances_path)
        .filter(pl.col("Timestamp").is_between(start, end))
        .sort("Timestamp")
        .group_by("Service")
        .agg([
            pl.len().alias("InstanceCount"),
            pl.col("QueueDepth").quantile(0.50).alias("P50QueueDepth"),
            pl.col("QueueDepth").quantile(0.95).alias("P95QueueDepth"),
            pl.col("QueueDepth").quantile(0.99).alias("P99QueueDepth"),
            pl.col("QueueDepth").std().alias("StdDevQueueDepth"),
        ])
        .sort("Service")
        .collect()
    )


def analysis_regional(requests_path: str, start: int, end: int) -> pl.DataFrame:
    grouped = (
        pl.scan_parquet(requests_path)
        .filter(pl.col("Timestamp").is_between(start, end))
        .group_by("Region")
        .agg([
            pl.len().alias("TotalRequests"),
            (pl.col("StatusCode") >= 500).sum().alias("ErrorCount"),
            (pl.col("StatusCode") >= 500).cast(pl.Float64).mean().alias("ErrorRate"),
            pl.col("DurationMs").quantile(0.50).alias("P50Duration"),
            pl.col("DurationMs").quantile(0.95).alias("P95Duration"),
        ])
        .sort("ErrorRate", descending=True, nulls_last=True)
        .with_columns(
            pl.arange(1, pl.len() + 1).cast(pl.Int64).alias("ErrorRank")
        )
        .collect()
    )
    return grouped


def analysis_grouped(requests_path: str, start: int, end: int) -> pl.DataFrame:
    return (
        pl.scan_parquet(requests_path)
        .filter(pl.col("Timestamp").is_between(start, end))
        .group_by("Service")
        .agg([
            pl.len().alias("TotalRequests"),
            (pl.col("StatusCode") >= 500).sum().cast(pl.Int64).alias("ErrorCount"),
            pl.col("DurationMs").mean().alias("AvgDurationMs"),
        ])
        .with_columns(
            (pl.col("ErrorCount").cast(pl.Float64) / pl.col("TotalRequests")).alias("ErrorRate")
        )
        .sort("Service")
        .select(["Service", "ErrorRate", "AvgDurationMs", "TotalRequests"])
        .collect()
    )


def main():
    args = parse_args()
    ds = Path(args.dataset)

    requests_path = ds / "requests.parquet"
    deployments_path = ds / "deployments.parquet"
    instances_path = ds / "instances.parquet"

    for p in [requests_path, deployments_path, instances_path]:
        if not p.exists():
            print(f"Error: {p} not found. Generate the dataset first.", file=sys.stderr)
            sys.exit(1)

    start, end = get_incident_ticks(args.scenario, str(requests_path))

    print(f"=== Benchmark: Polars {pl.__version__} ===")
    print(f"Dataset: {ds}")
    print()

    t0 = time.perf_counter()
    time_fn("Degradation Ordering", lambda: analysis_degradation(str(requests_path), start, end))
    time_fn("Deployment Correlation", lambda: analysis_deployment(str(requests_path), str(deployments_path), start, end))
    time_fn("Saturation Ordering", lambda: analysis_saturation(str(instances_path), start, end))
    time_fn("Regional Partitioning", lambda: analysis_regional(str(requests_path), start, end))
    time_fn("Grouped Aggregation", lambda: analysis_grouped(str(requests_path), start, end))
    total_ms = (time.perf_counter() - t0) * 1000

    print()
    print(f"  {'Total:':<24s} {total_ms:>8.1f} ms ({total_ms / 1000:.2f}s)")


if __name__ == "__main__":
    main()
